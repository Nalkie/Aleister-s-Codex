"""Retro TCG formats (Goat, Edison, HAT) -> src/formats.json.   Run from the project root:  python tools/fetch_formats.py
Sources (public APIs): Format Library (format dates, banlists, popular decks, recent events) and YGOPRODeck (card pool of Goat and Edison, Goat banlist).
Nothing here is generated by a model: every field is copied from those APIs. The build (tools/formats.py) works offline from this file."""
import json, os, sys, urllib.parse, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
H = {'User-Agent': 'Mozilla/5.0'}
FL = 'https://formatlibrary.com/api/'
FORMATS = {'goat': 'Goat', 'edison': 'Edison', 'hat': 'HAT'}


def get(u):
    return json.load(urllib.request.urlopen(urllib.request.Request(u, headers=H), timeout=120))


def ygo(params):
    out, off = [], 0
    while True:
        d = get('https://db.ygoprodeck.com/api/v7/cardinfo.php?' + params + f'&num=5000&offset={off}')
        out += d['data']
        nxt = d['meta'].get('next_page_offset')
        if not nxt:
            return out
        off = nxt


if __name__ == '__main__':
    os.chdir(ROOT)
    res = {}
    for key, name in FORMATS.items():
        info = get(FL + 'formats/' + key)['format']
        bl = get(FL + 'banlists/' + urllib.parse.quote(info['banlist']))
        ev = get(FL + 'events/recent/' + key)['events']
        res[key] = {
            'name': info['name'], 'date': info['date'], 'banlistName': info['banlist'], 'event': info['eventName'], 'description': info['description'],
            'banlist': {k: [x['cardName'] for x in bl[k]] for k in ('forbidden', 'limited', 'semiLimited')},
            'removed': [{'n': x['cardName'], 'was': x['previous']} for x in bl['unlimited']],
            'decks': [{'n': d['name'], 'art': [d['leftCardArtworkId'], d['centerCardArtworkId'], d['rightCardArtworkId']]} for d in get(FL + 'decks/popular/' + key)],
            'events': [{'n': e['name'], 'd': (e.get('startedAt') or '')[:10], 'size': e.get('size'), 'winner': e.get('winnerName'), 'community': e.get('communityName'), 'url': e.get('referenceUrl')} for e in ev],
        }
        print(key, {k: len(v) for k, v in res[key]['banlist'].items()}, len(res[key]['decks']), 'decks', len(res[key]['events']), 'events')
    res['goat']['pool'] = sorted(c['name'] for c in ygo('format=goat'))
    res['edison']['pool'] = sorted(c['name'] for c in ygo('format=edison'))
    gb = ygo('banlist=goat')
    res['goat']['ygoprodeckBan'] = {s: sorted(c['name'] for c in gb if (c.get('banlist_info') or {}).get('ban_goat') == s) for s in ('Forbidden', 'Limited', 'Semi-Limited')}
    json.dump(res, open('src/formats.json', 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    print('src/formats.json', {k: len(res[k].get('pool', [])) for k in res})
