"""Master Duel -> src/md.json.   Run from the project root:  python tools/fetch_md.py
Source (public API, no key): Master Duel Meta, https://www.masterduelmeta.com/api/v1 (the Master Duel sibling of Duel Links Meta).
  cards      : every card in the game (the format's pool) and the banlist (banStatus: Forbidden / Limited 1 / Limited 2)
  top-decks  : decks of the last WINDOW_DAYS days, from the ranked ladder and from tournaments, with the full list
  banlist-changes : every banlist update (date, announcement, article, card from -> to), the announced one that is not in force yet included
Nothing here is generated by a model: every field is copied from the API. The build (tools/md.py) works offline from src/md.json."""
import datetime, json, os, sys, time, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = 'https://www.masterduelmeta.com/api/v1/'
H = {'User-Agent': 'Mozilla/5.0'}


def today():       # the API dates decks in UTC: the local date is a day behind late in the evening west of Greenwich, and the newest deck would fall outside the window
    return datetime.datetime.now(datetime.timezone.utc).date()


WINDOW_DAYS = 42        # same window as the TCG / Genesys / OCG lists (tools/ygm.py)
PAGE = 3000             # the API caps `limit` at 3000


def get(path, tries=4):
    for i in range(tries):
        try:
            return json.load(urllib.request.urlopen(urllib.request.Request(B + path, headers=H), timeout=180))
        except Exception as e:
            if i == tries - 1:
                raise
            print('retry', path[:60], e, file=sys.stderr)
            time.sleep(3 * (i + 1))


def paged(path):
    out, skip = [], 0
    while True:
        part = get(f'{path}&limit={PAGE}&skip={skip}')
        out += part
        if len(part) < PAGE:
            return out
        skip += PAGE


LIMIT = {'Forbidden': 0, 'Limited 1': 1, 'Limited 2': 2}     # a missing status is 3 copies


def ban_changes(rows):
    out = []
    for r in rows:
        ch = [[x['card']['name'], LIMIT.get(x.get('from'), 3), LIMIT.get(x.get('to'), 3)] for x in r.get('changes') or [] if isinstance(x.get('card'), dict)]
        if r.get('date') and ch:
            art = r.get('linkedArticle')
            out.append({'d': r['date'][:10], 'announced': (r.get('announced') or '')[:10], 'article': art.get('url') if isinstance(art, dict) else None, 'ch': ch})
    return sorted(out, key=lambda c: c['d'])


def deck_cards(rows):
    return [[r['card']['name'], r['amount']] for r in rows or [] if r.get('card')]


def fetch():
    cards = paged('cards?fields=name,banStatus&sort=_id')       # `_id` always comes back
    ban = {'Forbidden': [], 'Limited': [], 'SemiLimited': []}
    key = {'Forbidden': 'Forbidden', 'Limited 1': 'Limited', 'Limited 2': 'SemiLimited'}
    for c in cards:
        if c.get('banStatus') in key:
            ban[key[c['banStatus']]].append(c['name'])
    by_id = {c['_id']: c['name'] for c in cards}
    art = {t['name']: by_id[t['card']] for t in paged('deck-types?fields=name,card&sort=_id') if isinstance(t.get('card'), str) and t['card'] in by_id}     # the card Master Duel Meta shows for each deck type
    since = (today() - datetime.timedelta(days=WINDOW_DAYS)).isoformat()
    decks, skip = [], 0
    while True:
        part = get(f'top-decks?sort=-created&limit={PAGE}&skip={skip}&fields=created,author,deckType,main,extra,side,rankedType,tournamentType,tournamentPlacement,url')
        for d in part:
            if d['created'][:10] < since:
                break
            decks.append({'id': d['_id'], 'd': d['created'][:10], 'who': d['author'] if isinstance(d.get('author'), str) else (d.get('author') or {}).get('username') or '',
                          'type': (d.get('deckType') or {}).get('name') or '' if isinstance(d.get('deckType'), dict) else '',
                          'ranked': d['rankedType'] if d.get('rankedType') else None,
                          'tour': d['tournamentType'] if d.get('tournamentType') else None, 'place': d.get('tournamentPlacement'),
                          'url': d.get('url') or '', 'main': deck_cards(d.get('main')), 'extra': deck_cards(d.get('extra')), 'side': deck_cards(d.get('side'))})
        else:
            if len(part) == PAGE:
                skip += PAGE
                continue
        break
    for d in decks:       # keep only what the build reads
        for k, src in (('ranked', ('name', 'statsWeight', 'includeInStats')), ('tour', ('name', 'statsWeight'))):
            d[k] = {a: d[k].get(a) for a in src} if d[k] else None
    changes = ban_changes(paged('banlist-changes?sort=date&fields=date,announced,changes,linkedArticle'))
    return {'source': B, 'fetched': today().isoformat(), 'window': [since, today().isoformat()],
            'art': art, 'pool': sorted({c['name'] for c in cards}), 'ban': {k: sorted(set(v)) for k, v in ban.items()}, 'changes': changes, 'decks': decks}


if __name__ == '__main__':
    os.chdir(ROOT)
    res = fetch()
    open('src/md.json', 'w', encoding='utf-8').write(json.dumps(res, ensure_ascii=False, separators=(',', ':')))
    print('src/md.json', {'pool': len(res['pool']), 'changes': len(res['changes']), 'ban': {k: len(v) for k, v in res['ban'].items()}, 'decks': len(res['decks']), 'art': len(res['art']), 'window': res['window']})
